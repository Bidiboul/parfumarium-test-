/**
 * Jeton canonique d'un terme (note ou accord), à partir des tables
 * explicites puis des règles par mot-clé. Retourne null si rien ne
 * correspond : le terme sera alors affiché mais non utilisé pour le
 * rapprochement.
 */
export function canonOf(term, explicit) {
  const key = String(term).toLowerCase().trim();
  if (explicit && explicit[key]) return explicit[key][1] ?? explicit[key];
  for (const [pattern, canon] of KEYWORD_RULES) {
    if (pattern.test(key)) return canon;
  }
  return null;
}

/** Libellé français d'une note (repli : le terme d'origine capitalisé). */
export function frenchLabel(term, table) {
  const key = String(term).toLowerCase().trim();
  if (table[key]) return table[key][0];
  return key.charAt(0).toUpperCase() + key.slice(1);
}
